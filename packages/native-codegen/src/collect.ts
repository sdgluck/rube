/**
 * Rube's native contract, as the named schemas `zod-to-swift` and
 * `zod-to-kotlin` take, plus the one thing those libraries rightly know
 * nothing about: tRPC endpoints.
 *
 * Outputs come from `NATIVE_PROCEDURES` (the same objects the routers attach
 * with `.output()`); inputs from each procedure's own `.input()`, read off the
 * router by the CLI, because duplicating them into contracts would be a second
 * copy free to drift from the one tRPC validates.
 *
 * Pure over its arguments, so the tests drive it with plain zod schemas.
 */
import type { z } from "zod";
import { pascal, camel, type NamedSchema } from "zod-native-ir";
import { generateSwift } from "zod-to-swift";
import { generateKotlin } from "zod-to-kotlin";

export interface ProcedureSource {
  router: "portal" | "admin";
  path: string;
  kind: "query" | "mutation";
  input: z.ZodType | undefined;
  output: z.ZodType | null;
}

const NAMESPACE = { portal: "Portal", admin: "Admin" } as const;

const typeName = (path: string, which: "Input" | "Output") => `${pascal(path)}${which}`;

/**
 * The shape an output wraps, named after the procedure rather than the alias:
 * `LeavingSoonOutput = [LeavingSoonItem]`, `RulesRunDetailOutput =
 * RulesRunDetail?`, `CleanupCountsOutput = [String: CleanupCountsValue]`.
 */
const itemName = (root: string, wrapper: "array" | "record" | "nullable") => {
  const base = root.endsWith("Output") ? root.slice(0, -"Output".length) : root;
  if (wrapper === "array") return `${base}Item`;
  return wrapper === "nullable" && base !== root ? base : `${base}Value`;
};

export function namedSchemas(sources: ProcedureSource[]): NamedSchema[] {
  return sources.flatMap((s) => {
    const namespace = NAMESPACE[s.router];
    const named: NamedSchema[] = [];
    if (s.input) named.push({ namespace, name: typeName(s.path, "Input"), schema: s.input, io: "input" });
    if (s.output) named.push({ namespace, name: typeName(s.path, "Output"), schema: s.output, io: "output" });
    return named;
  });
}

const HEADER = [
  "Generated by `pnpm native:codegen` from @rube/contracts/native-api.",
  "Do not edit — change the schema and regenerate. `pnpm verify` fails if this is stale.",
];

export function emitSwift(sources: ProcedureSource[]): string {
  return generateSwift(namedSchemas(sources), {
    header: [...HEADER, "swiftlint:disable all"],
    // `Support.swift` in RubeModels defines these beside `Endpoint`.
    emitSupport: false,
    itemName,
    afterNamespace: (ns, refs) => {
      const procs = sources.filter((s) => NAMESPACE[s.router] === ns);
      return [
        `public enum ${ns}API {`,
        ...procs.map((p) => {
          const input = p.input ? refs.get(typeName(p.path, "Input"))! : "NoInput";
          const output = p.output ? refs.get(typeName(p.path, "Output"))! : "NoOutput";
          return `    public static let ${camel(p.path)} = Endpoint<${input}, ${output}>(path: ${JSON.stringify(p.path)}, kind: .${p.kind})`;
        }),
        "}",
      ];
    },
  });
}

export function emitKotlin(sources: ProcedureSource[]): string {
  return generateKotlin(namedSchemas(sources), {
    packageName: "fyi.rube.model",
    header: HEADER,
    suppress: ["unused", "RedundantVisibilityModifier", "ktlint"],
    itemName,
    afterNamespace: (ns, refs) => {
      const procs = sources.filter((s) => NAMESPACE[s.router] === ns);
      return [
        `object ${ns}Api {`,
        ...procs.map((p) => {
          const input = p.input ? refs.get(typeName(p.path, "Input"))!.serializer : "NoInput.serializer()";
          const output = p.output ? refs.get(typeName(p.path, "Output"))!.serializer : "NoOutput.serializer()";
          return `    val ${camel(p.path)} = Endpoint(${JSON.stringify(p.path)}, Endpoint.Kind.${p.kind.toUpperCase()}, ${input}, ${output})`;
        }),
        "}",
      ];
    },
  });
}
