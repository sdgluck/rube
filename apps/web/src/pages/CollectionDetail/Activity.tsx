import { Link } from "react-router-dom";
import { trpc } from "#/trpc";
import CardSection from "#components/CardSection";
import RelativeTime from "#components/RelativeTime";
import EmptyState from "#components/EmptyState";
import styles from "#/styles/shared.module.css";
import { TYPE_LABELS } from "#pages/Rules/constants";
import { useCollection } from "./context.ts";
import local from "./CollectionDetail.module.css";

/** How the summary got there, in words rather than the stored enum. */
const SUMMARY_SOURCES: Record<string, string> = {
  template: "Written by Rube from a template",
  llm: "Written by the configured language model",
  custom: "Taken from the rule's custom summary",
  source: "Provided by the source (TMDb, a list, or the pack)",
};

export default function Activity() {
  const { ratingKey, collection, openStudio } = useCollection();

  const artworkQuery = trpc.collections.artworkState.useQuery({ ratingKey }, { refetchOnWindowFocus: false });
  const ruleQuery = trpc.collections.owningRule.useQuery({ ratingKey }, { refetchOnWindowFocus: false });

  const artwork = artworkQuery.data;
  const rule = ruleQuery.data;

  return (
    <>
      <CardSection title="Where this came from" className={styles.group} titleClassName={styles.groupTitle}>
        {rule ? (
          <>
            <div className={local.factRow}>
              <span className={local.factName}>Generated by</span>
              <span className={local.factValue}>
                <Link to={`/rules?q=${encodeURIComponent(rule.name)}`} className={styles.metaChipLink}>
                  {rule.name}
                </Link>
              </span>
            </div>
            <div className={local.factRow}>
              <span className={local.factName}>Rule type</span>
              <span className={local.factValue}>{TYPE_LABELS[rule.type] ?? rule.type}</span>
            </div>
          </>
        ) : (
          <p className={styles.hint}>Not made by a Rube rule, so nothing rewrites it.</p>
        )}
        <div className={local.factRow}>
          <span className={local.factName}>Last read from Plex</span>
          <span className={local.factValue}>
            <RelativeTime timestamp={collection.syncedAt} />
          </span>
        </div>
        {collection.addedAt && (
          <div className={local.factRow}>
            <span className={local.factName}>Created in Plex</span>
            <span className={local.factValue}>
              <RelativeTime timestamp={collection.addedAt} seconds />
            </span>
          </div>
        )}
      </CardSection>

      <CardSection title="Artwork and summary" className={styles.group} titleClassName={styles.groupTitle}>
        {artworkQuery.isLoading ? (
          <p className={styles.hint}>Loading…</p>
        ) : !artwork ? (
          <EmptyState
            icon="film"
            title="Rube hasn't written to this collection"
            description="A poster chosen here stops rules replacing it."
            action={
              <button type="button" className={styles.buttonSecondary} onClick={openStudio}>
                Change poster
              </button>
            }
          />
        ) : (
          <>
            <div className={local.factRow}>
              <span className={local.factName}>Summary</span>
              <span className={local.factValue}>
                {artwork.summaryLockedAt
                  ? "Edited by hand — Rube no longer writes it"
                  : (SUMMARY_SOURCES[artwork.summarySource] ?? "Not written by Rube")}
              </span>
            </div>
            <div className={local.factRow}>
              <span className={local.factName}>Poster</span>
              <span className={local.factValue}>
                {artwork.posterLockedAt ? (
                  <>
                    Chosen by hand <RelativeTime timestamp={artwork.posterLockedAt} /> — no job will replace it
                  </>
                ) : artwork.posterUploadedAt ? (
                  <>
                    Generated by Rube <RelativeTime timestamp={artwork.posterUploadedAt} />
                  </>
                ) : (
                  "Left as Plex made it"
                )}
              </span>
            </div>
            {/* The one fact "revert artwork" depends on, stated plainly rather
                than implied by a button that might restore nothing. */}
            <div className={local.factRow}>
              <span className={local.factName}>Artwork found here first</span>
              <span className={local.factValue}>
                {artwork.priorThumb ? "Yes — still among the collection's posters in Plex" : "None"}
              </span>
            </div>
            <div className={local.factRow}>
              <span className={local.factName}>Ledger updated</span>
              <span className={local.factValue}>
                <RelativeTime timestamp={artwork.updatedAt} />
              </span>
            </div>
          </>
        )}
      </CardSection>
    </>
  );
}
